#!/usr/bin/env python3
"""Turn a draw.io diagram into Markdown text that an agent can read and cite.

    python3 tools/drawio_text.py spec/sources/fifo_block.drawio > spec/sources/fifo_block.drawio.md

Accepts `.drawio` / `.xml` (plain or compressed pages) and `.drawio.svg` (diagram embedded in the
SVG `content` attribute). `.drawio.png` is not supported: export it as `.drawio` or `.drawio.svg`.

Output, per page: shapes (id, label, container, custom properties) and connectors
(source -> target, label). Connectors with a missing end are listed separately: a line that only
*looks* attached in the picture is a gap the spec-analyst must raise, not a connection.
Standard library only; the human runs it (agents have no Bash for it).
"""
from __future__ import annotations

import base64
import html
import re
import sys
import urllib.parse
import xml.etree.ElementTree as ET
import zlib
from pathlib import Path


def _decode_page(text: str) -> ET.Element:
    """Compressed page = base64(raw deflate(urlencode(xml)))."""
    raw = zlib.decompress(base64.b64decode(text.strip()), -15)
    return ET.fromstring(urllib.parse.unquote(raw.decode("utf-8")))


def _mxfile(path: Path) -> ET.Element:
    data = path.read_text(encoding="utf-8")
    root = ET.fromstring(data)
    if root.tag.endswith("svg"):
        content = root.get("content")
        if not content:
            raise ValueError(f"{path}: SVG has no embedded draw.io diagram (export with 'Include a copy of my diagram')")
        root = ET.fromstring(html.unescape(content) if content.lstrip().startswith("&lt;") else content)
    return root


def pages(path: Path) -> list[tuple[str, ET.Element]]:
    root = _mxfile(path)
    if root.tag == "mxGraphModel":
        return [("Page-1", root)]
    if root.tag != "mxfile":
        raise ValueError(f"{path}: not a draw.io file (root <{root.tag}>)")
    out = []
    for i, d in enumerate(root.findall("diagram"), 1):
        model = d.find("mxGraphModel")
        if model is None:
            model = _decode_page(d.text or "")
        out.append((d.get("name") or f"Page-{i}", model))
    return out


def clean(label: str | None) -> str:
    """Strip HTML from a label; keep line breaks as ' / '."""
    if not label:
        return ""
    s = re.sub(r"<br\s*/?>|</div>|</p>", "\n", label, flags=re.I)
    s = html.unescape(re.sub(r"<[^>]+>", "", s))
    return " / ".join(p.strip() for p in s.splitlines() if p.strip())


def cells(model: ET.Element) -> list[dict]:
    """Flatten mxCell, including those wrapped in <UserObject>/<object> (label + custom properties)."""
    out = []
    root = model.find("root")
    for el in (root if root is not None else []):
        if el.tag == "mxCell":
            cell, label, props = el, el.get("value"), {}
        elif el.tag in ("UserObject", "object"):
            cell = el.find("mxCell")
            if cell is None:
                continue
            label = el.get("label")
            props = {k: v for k, v in el.attrib.items() if k not in ("id", "label", "placeholders")}
        else:
            continue
        out.append({"id": el.get("id"), "label": clean(label), "props": props, "parent": cell.get("parent"),
                    "vertex": cell.get("vertex") == "1", "edge": cell.get("edge") == "1",
                    "source": cell.get("source"), "target": cell.get("target"), "style": cell.get("style") or ""})
    return out


def _name(c: dict | None, cid: str | None) -> str:
    if c is None:
        return f"?{cid}" if cid else "(none)"
    return f"{c['label'] or '(no label)'} [{c['id']}]"


def render(path: Path) -> str:
    lines = [f"# {path.name} (draw.io, text extract)", "",
             f"Generated by `tools/drawio_text.py` from `{path}`. Cite as `{path.name}#<page>/<id>`.", ""]
    for pname, model in pages(path):
        cs = cells(model)
        by_id = {c["id"]: c for c in cs}
        verts = [c for c in cs if c["vertex"]]
        edges = [c for c in cs if c["edge"]]
        # edge labels are often child text cells of the edge
        edge_text = {}
        for c in verts:
            p = by_id.get(c["parent"])
            if p and p["edge"] and c["label"]:
                edge_text.setdefault(p["id"], []).append(c["label"])
        shapes = [c for c in verts if not (by_id.get(c["parent"]) or {}).get("edge")]
        lines += [f"## Page: {pname}", "", "### Shapes", "", "| id | label | inside | properties |", "|---|---|---|---|"]
        for c in shapes:
            par = by_id.get(c["parent"])
            inside = _name(par, c["parent"]) if par and par["vertex"] else ""
            props = ", ".join(f"{k}={v}" for k, v in c["props"].items())
            lines.append(f"| {c['id']} | {c['label']} | {inside} | {props} |")
        lines += ["", "### Connectors", "", "| id | from | to | label |", "|---|---|---|---|"]
        dangling = []
        for e in edges:
            label = " / ".join(x for x in [e["label"], *edge_text.get(e["id"], [])] if x)
            if not e["source"] or not e["target"] or e["source"] not in by_id or e["target"] not in by_id:
                dangling.append((e, label))
                continue
            lines.append(f"| {e['id']} | {_name(by_id[e['source']], e['source'])} | "
                         f"{_name(by_id[e['target']], e['target'])} | {label} |")
        if dangling:
            lines += ["", "### Connectors with a missing end (not attached in the diagram: raise as a gap)", ""]
            for e, label in dangling:
                lines.append(f"- {e['id']}: from {_name(by_id.get(e['source']), e['source'])} "
                             f"to {_name(by_id.get(e['target']), e['target'])}" + (f", label \"{label}\"" if label else ""))
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print(__doc__.strip().splitlines()[2].strip(), file=sys.stderr)
        return 2
    try:
        sys.stdout.write(render(Path(argv[1])))
    except (OSError, ValueError, ET.ParseError, zlib.error) as exc:
        print(f"drawio_text: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
